# ----------------------------------------------------------------------
def get_job_description(url):
    """
    Fetches the content of a URL and extracts text using BeautifulSoup.
    This is a basic scraper and may not work perfectly for all websites.
    """
    try:
        headers = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/91.0.4472.124 Safari/537.36'}
        response = requests.get(url, headers=headers, timeout=10)
        response.raise_for_status()

        soup = BeautifulSoup(response.text, 'html.parser')

        # Try to find common job description containers using class or id names
        job_description_element = soup.find('div', class_=re.compile("description|details", re.I)) or \
                                  soup.find('div', id=re.compile("description", re.I)) or \
                                  soup.find('main') # Fallback to main content area

        if job_description_element:
            return job_description_element.get_text(separator='\n', strip=True)
        else:
            # Final fallback if no specific container is found
            return soup.body.get_text(separator='\n', strip=True)

    except requests.exceptions.RequestException as e:
        return f"Error: Could not fetch page content. {e}"
    except Exception as e:
        return f"Error: An unknown error occurred during scraping. {e}"


# ----------------------------------------------------------------------
#  MAIN SCRIPT LOGIC
# ----------------------------------------------------------------------
def search_and_process_jobs(query, num_jobs=20):
    """
    Main function to orchestrate the job search, scraping, and saving process.
    """
    all_job_results = []
    # Google Custom Search API returns 10 results at a time.
    # To get 20, we need to make 2 API calls, starting at result 1 and 11.
    pages_to_fetch = (num_jobs // 10)

    for page in range(pages_to_fetch):
        start_index = page * 10 + 1

        # ----------------------------------------------------------------------
        #  SECTION 2: API CALL
        # ----------------------------------------------------------------------
        print(f"\nFetching page {page + 1} of results (starting at item {start_index})...")
        url = "https://www.googleapis.com/customsearch/v1"
        params = {
            'key': API_KEY,
            'cx': SEARCH_ENGINE_ID,
            'q': query,
            'start': start_index
        }

        try:
            response = requests.get(url, params=params)
            response.raise_for_status()
            search_results = response.json()
        except requests.exceptions.RequestException as e:
            print(f"FATAL: API call failed: {e}")
            return # Exit if the API call fails

        if 'items' not in search_results:
            print("No more results found. Stopping.")
            break

        # ----------------------------------------------------------------------
        #  SECTION 3: PARSING API RESPONSE
        # ----------------------------------------------------------------------
        for i, item in enumerate(search_results['items'], start=start_index):
            full_title = item.get('title', 'N/A')
            link = item.get('link', 'N/A')
            print(f"  -> Processing result #{i}: {full_title}")

            # Basic parsing of the title string (e.g., "Job Title - Company - Location")
            parts = [p.strip() for p in full_title.split('-')]
            job_title = parts[0] if len(parts) > 0 else 'N/A'
            company = parts[1] if len(parts) > 1 else 'N/A'
            location = parts[2] if len(parts) > 2 else 'N/A'

            # Fetch the full description
            description = "Could not fetch description."
            if link != 'N/A':
                description = get_job_description(link)

            # Assemble the job data dictionary
            job_data = {
                "title": job_title,
                "company": company,
                "location": location,
                "url": link,
                "description": description
            }
            all_job_results.append(job_data)

    if not all_job_results:
        print("No jobs were found or processed.")
        return

    # ----------------------------------------------------------------------
    #  SECTION 4: JSON SAVING
    # ----------------------------------------------------------------------
    output_filename = 'jobs.json'
    try:
        with open(output_filename, 'w', encoding='utf-8') as f:
            json.dump(all_job_results, f, indent=4, ensure_ascii=False)
        print(f"\n✅ Success! {len(all_job_results)} jobs saved to '{output_filename}'")
    except IOError as e:
        print(f"FATAL: Could not write to file '{output_filename}'. Error: {e}")


