import requests
import re
from bs4 import BeautifulSoup

def fetch_and_clean_text(url):
    """
    Fetches HTML from a URL, cleans it, and extracts the primary text.

    Args:
        url (str): The URL of the webpage to process.

    Returns:
        str: The cleaned text, or None if fetching or processing fails.
    """
    try:
        # Set a User-Agent to mimic a browser, as some sites (incl. SEC)
        # might block simple script requests.
        # SEC EDGAR requires a User-Agent that includes contact info (e.g., email).
        # *** REPLACE 'your.email@example.com' WITH YOUR ACTUAL EMAIL ***
        headers = {
            'User-Agent': 'Sample Company Name your.email@example.com',
            'Accept': 'text/html,application/xhtml+xml,application/xml;q=0.9,image/webp,*/*;q=0.8',
            'Accept-Language': 'en-US,en;q=0.5',
            'Accept-Encoding': 'gzip, deflate, br',
            'Connection': 'keep-alive',
            'Upgrade-Insecure-Requests': '1',
            'Host': 'www.sec.gov' # Explicitly setting host can sometimes help
        }

        # 1. Fetch the HTML content
        print(f"Fetching content from {url}...")
        response = requests.get(url, headers=headers)

        # Raise an exception for bad status codes (like 404 or 500)
        response.raise_for_status()

        print("Content fetched successfully. Parsing HTML...")
        soup = BeautifulSoup(response.text, 'html.parser')

        # 2. Find the main content
        # EDGAR filings often wrap the main document in a <text> tag
        # (even in .htm files). This is a good first target.
        main_content = soup.find('text')

        # If no <text> tag is found, fall back to the <body>
        if not main_content:
            main_content = soup.body

        # If still no body, use the whole soup object
        if not main_content:
            main_content = soup

        # 3. Remove HTML tags, scripts, styles, tables, etc.
        print("Cleaning HTML...")
        tags_to_remove = [
            'script',  # Remove scripts
            'style',   # Remove style sections
            'table',   # Remove tables (as requested)
            'nav',     # Remove navigation elements
            'header',  # Remove headers
            'footer'   # Remove footers
        ]

        for tag in main_content.find_all(tags_to_remove):
            tag.extract() # Remove the tag and all its contents

        # 4. Extract the primary textual content
        # .get_text() extracts all text from the remaining tags.
        # separator=' ' ensures that text from different tags is separated by a space.
        text = main_content.get_text(separator=' ')

        # 5. Normalize whitespace
        # - Replace all whitespace (spaces, newlines, tabs) with a single space
        text = re.sub(r'\s+', ' ', text)
        # - Remove leading/trailing whitespace
        text = text.strip()

        print("Cleaning complete.")
        return text

    except requests.exceptions.RequestException as e:
        print(f"Error fetching URL: {e}")
        return None
    except Exception as e:
        print(f"An error occurred during parsing: {e}")
        return None

def main():
    """
    Main function to run the text extraction and save the output.
    """
    # The URL you provided
    target_url = "https://www.sec.gov/Archives/edgar/data/1045810/000104581014000030/nvda-2014x10k.htm"

    # The name of the output file
    output_filename = "cleaned_filing_text.txt"

    cleaned_text = fetch_and_clean_text(target_url)

    if cleaned_text:
        # 6. Format the cleaned text for readability and AI input
        # Save the result to a file, which is ideal for AI input
        try:
            with open(output_filename, 'w', encoding='utf-8') as f:
                f.write(cleaned_text)

            print(f"\nSuccessfully extracted and cleaned text.")
            print(f"Output saved to: {output_filename}")

            # Print a preview of the cleaned text
            print("\n--- First 500 characters of cleaned text ---")
            print(cleaned_text[:500] + "...")
            print("--------------------------------------------------")

        except IOError as e:
            print(f"Error writing to file {output_filename}: {e}")

if __name__ == "__main__":
    main()

