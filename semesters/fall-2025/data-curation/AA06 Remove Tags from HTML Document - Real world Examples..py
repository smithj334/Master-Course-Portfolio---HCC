import requests
import re
import os  # <-- We import the 'os' module to check file sizes
from bs4 import BeautifulSoup

def fetch_html(url):
    """
    Fetches HTML content from a URL.

    Args:
        url (str): The URL of the webpage to process.

    Returns:
        requests.Response: The response object, or None if fetching fails.
    """
    try:
        # Set a User-Agent to mimic a browser
        # *** REPLACE 'your.email@example.com' WITH YOUR ACTUAL EMAIL ***
        headers = {
            'User-Agent': 'Sample Company Name your.email@example.com',
            'Accept': 'text/html,application/xhtml+xml,application/xml;q=0.9,image/webp,*/*;q=0.8',
            'Accept-Language': 'en-US,en;q=0.5',
            'Accept-Encoding': 'gzip, deflate, br',
            'Connection': 'keep-alive',
            'Upgrade-Insecure-Requests': '1',
            'Host': 'www.sec.gov'
        }

        print(f"Fetching content from {url}...")
        response = requests.get(url, headers=headers)
        response.raise_for_status() # Raise exception for bad status
        print("Content fetched successfully.")
        return response

    except requests.exceptions.RequestException as e:
        print(f"Error fetching URL: {e}")
        return None

def clean_html_text(html_content):
    """
    Parses and cleans HTML content to extract primary text.

    Args:
        html_content (str): The raw HTML content string.

    Returns:
        str: The cleaned text.
    """
    try:
        print("Parsing HTML...")
        soup = BeautifulSoup(html_content, 'html.parser')

        # Find the main content
        main_content = soup.find('text')
        if not main_content:
            main_content = soup.body
        if not main_content:
            main_content = soup

        # Remove HTML tags, scripts, styles, tables, etc.
        print("Cleaning HTML...")
        tags_to_remove = ['script', 'style', 'table', 'nav', 'header', 'footer']

        for tag in main_content.find_all(tags_to_remove):
            tag.extract()

        # Extract the primary textual content
        text = main_content.get_text(separator=' ')

        # Normalize whitespace
        text = re.sub(r'\s+', ' ', text)
        text = text.strip()

        print("Cleaning complete.")
        return text

    except Exception as e:
        print(f"An error occurred during parsing: {e}")
        return ""

def main():
    """
    Main function to fetch, clean, save, and compare file sizes.
    """
    target_url = "https://www.sec.gov/Archives/edgar/data/1045810/000104581014000030/nvda-2014x10k.htm"

    # Define file names
    original_filename = "original_filing.htm"
    cleaned_filename = "cleaned_filing_text.txt"

    # 1. Fetch the HTML
    response = fetch_html(target_url)

    if response:
        try:
            # 2. Save the original HTML
            # We use response.content (bytes) for an accurate file save
            with open(original_filename, 'wb') as f:
                f.write(response.content)
            print(f"Original HTML saved to: {original_filename}")

            # 3. Clean the HTML (use response.text for string-based parsing)
            cleaned_text = clean_html_text(response.text)

            # 4. Save the cleaned text
            with open(cleaned_filename, 'w', encoding='utf-8') as f:
                f.write(cleaned_text)
            print(f"Cleaned text saved to: {cleaned_filename}")

            # 5. Compare File Sizes (This is the new part)
            print("\n--- File Size Comparison ---")

            # Get size in bytes using os.path.getsize()
            original_size = os.path.getsize(original_filename)
            cleaned_size = os.path.getsize(cleaned_filename)

            # Calculate reduction
            reduction_bytes = original_size - cleaned_size
            reduction_percent = (reduction_bytes / original_size) * 100 if original_size > 0 else 0

            # Format for readability
            print(f"Original HTML ({original_filename}):\t {original_size:,.0f} bytes ({original_size/1024:,.2f} KB)")
            print(f"Cleaned Text ({cleaned_filename}):\t {cleaned_size:,.0f} bytes ({cleaned_size/1024:,.2f} KB)")
            print(f"Total reduction:\t\t\t {reduction_bytes:,.0f} bytes")
            print(f"Cleaned file is {reduction_percent:.2f}% smaller.")
            print("---------------------------------")

            # Print a preview
            print("\n--- First 500 characters of cleaned text ---")
            print(cleaned_text[:500] + "...")
            print("--------------------------------------------------")

        except IOError as e:
            print(f"Error writing to file: {e}")
        except Exception as e:
            print(f"An error occurred: {e}")

if __name__ == "__main__":
    main()